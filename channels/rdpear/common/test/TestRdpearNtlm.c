#include <winpr/crt.h>
#include <winpr/string.h>

#include "rdpear-common/rdpear_ntlm.h"

/* Known-answer vectors from [MS-NLMP] 4.2 (User "User", Domain "Domain", Password "Password",
 * server challenge 0x0123456789abcdef). */

static BOOL eq(const char* what, const BYTE* got, const BYTE* exp, size_t len)
{
	if (memcmp(got, exp, len) == 0)
		return TRUE;
	(void)fprintf(stderr, "%s mismatch\n", what);
	return FALSE;
}

int TestRdpearNtlm(int argc, char* argv[])
{
	WINPR_UNUSED(argc);
	WINPR_UNUSED(argv);

	const WCHAR password[] = { 'P', 'a', 's', 's', 'w', 'o', 'r', 'd' };
	const WCHAR user[] = { 'U', 's', 'e', 'r' };
	const WCHAR domain[] = { 'D', 'o', 'm', 'a', 'i', 'n' };
	const BYTE challenge[8] = { 0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef };

	const BYTE ntowfv1_exp[16] = { 0xa4, 0xf4, 0x9c, 0x40, 0x65, 0x10, 0xbd, 0xca,
		                           0xb6, 0x82, 0x4e, 0xe7, 0xc3, 0x0f, 0xd8, 0x52 };
	const BYTE ntowfv2_exp[16] = { 0x0c, 0x86, 0x8a, 0x40, 0x3b, 0xfd, 0x7a, 0x93,
		                           0xa3, 0x00, 0x1e, 0xf2, 0x2e, 0xf0, 0x2e, 0x3f };
	const BYTE ntresp_v1_exp[24] = { 0x67, 0xc4, 0x30, 0x11, 0xf3, 0x02, 0x98, 0xa2,
		                             0xad, 0x35, 0xec, 0xe6, 0x4f, 0x16, 0x33, 0x1c,
		                             0x44, 0xbd, 0xbe, 0xd9, 0x27, 0x84, 0x1f, 0x94 };
	const BYTE usk_v1_exp[16] = { 0xd8, 0x72, 0x62, 0xb0, 0xcd, 0xe4, 0xb1, 0xcb,
		                          0x74, 0x99, 0xbe, 0xcc, 0xcd, 0xf1, 0x07, 0x84 };
	const BYTE ntproof_v2_exp[16] = { 0x68, 0xcd, 0x0a, 0xb8, 0x51, 0xe5, 0x1c, 0x96,
		                              0xaa, 0xbc, 0x92, 0x7b, 0xeb, 0xef, 0x6a, 0x1c };
	const BYTE sbk_v2_exp[16] = { 0x8d, 0xe4, 0x0c, 0xca, 0xdb, 0xc1, 0x4a, 0x82,
		                          0xf1, 0x5c, 0xb0, 0xad, 0x0d, 0xe9, 0x5c, 0xa3 };
	/* temp blob from [MS-NLMP] 4.2.4.1 (time 0, client challenge 0xaa.., Domain/Server TargetInfo)
	 */
	const BYTE temp[] = { 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		                  0x00, 0x00, 0x00, 0x00, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa,
		                  0x00, 0x00, 0x00, 0x00, 0x02, 0x00, 0x0c, 0x00, 0x44, 0x00, 0x6f, 0x00,
		                  0x6d, 0x00, 0x61, 0x00, 0x69, 0x00, 0x6e, 0x00, 0x01, 0x00, 0x0c, 0x00,
		                  0x53, 0x00, 0x65, 0x00, 0x72, 0x00, 0x76, 0x00, 0x65, 0x00, 0x72, 0x00,
		                  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 };

	BYTE ntowfv1[16] = { 0 };
	BYTE ntowfv2[16] = { 0 };
	BYTE ntresp[24] = { 0 };
	BYTE usk[16] = { 0 };
	BYTE ntproof[16] = { 0 };
	BYTE sbk[16] = { 0 };

	if (!rdpear_ntowf_v1(password, ARRAYSIZE(password), ntowfv1) ||
	    !eq("NTOWFv1", ntowfv1, ntowfv1_exp, 16))
		return -1;

	if (!rdpear_ntowf_v2(ntowfv1, user, ARRAYSIZE(user), domain, ARRAYSIZE(domain), ntowfv2) ||
	    !eq("NTOWFv2", ntowfv2, ntowfv2_exp, 16))
		return -1;

	if (!rdpear_ntlm_v1_response(ntowfv1, challenge, ntresp) ||
	    !eq("NTLMv1 NtChallengeResponse", ntresp, ntresp_v1_exp, 24))
		return -1;

	if (!rdpear_ntlm_v1_user_session_key(ntowfv1, usk) ||
	    !eq("NTLMv1 user session key", usk, usk_v1_exp, 16))
		return -1;

	if (!rdpear_ntlm_v2_response(ntowfv2, challenge, temp, sizeof(temp), ntproof, sbk) ||
	    !eq("NTLMv2 NTProofStr", ntproof, ntproof_v2_exp, 16) ||
	    !eq("NTLMv2 session base key", sbk, sbk_v2_exp, 16))
		return -1;

	return 0;
}
